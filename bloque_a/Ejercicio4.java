public class Ejercicio4 {
    public static void main(String[] args) {
        // Imprimir números del 1 al 20 usando bucle 'for'
        for (int i = 1; i <= 20; i++) {
            System.out.println(i);
        }

        // Imprimir números del 20 al 1 usando bucle 'while'
        int j = 20;
        while (j >= 1) {
            System.out.println(j);
            j--;
        }
    }
}